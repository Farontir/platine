//! Brush presets: named brush settings. The shipped ones are generated here by code;
//! the application keeps the user's.
//!
//! A shipped preset sets how the brush behaves (tip, dynamics, pressure) and keeps the
//! painted material; a user preset also records the material.

use patine_core::channel::Channel;
use patine_core::layer::{ProceduralRef, Projection};
use patine_core::stroke::{BrushSnapshot, Curve, PressureCurves};
use serde::{Deserialize, Serialize};

/// The painted material of a user preset.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PresetMaterial {
    /// Channels and whether they are painted, with their values.
    pub channels: Vec<(Channel, bool, [f32; 4])>,
    /// Gray painted into masks.
    pub mask_value: f32,
    /// Procedural material painted on layers instead of the values.
    pub procedural: Option<ProceduralRef>,
    /// Procedural pattern painted into masks instead of the gray.
    pub mask_procedural: Option<ProceduralRef>,
    /// Projection of the procedurals.
    pub projection: Projection,
}

/// Brush settings of a preset.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct BrushSettings {
    /// Diameter, in viewport pixels.
    pub size: f32,
    /// Paint deposited per dab.
    pub flow: f32,
    /// Maximum opacity of a stroke.
    pub opacity: f32,
    /// Edge hardness.
    pub hardness: f32,
    /// Distance between dabs, as a fraction of the size.
    pub spacing: f32,
    /// Rotation of the dabs, radians.
    pub angle: f32,
    /// Lazy mouse string, pixels.
    pub smoothing: f32,
    /// Shipped alpha, by identifier; `None` for a round dab.
    pub alpha: Option<String>,
    /// Random size variation, 0 to 1.
    pub size_jitter: f32,
    /// Random rotation, radians.
    pub angle_jitter: f32,
    /// Random flow variation, 0 to 1.
    pub flow_jitter: f32,
    /// Random offset across the stroke, as a fraction of the size.
    pub scatter: f32,
    /// Dabs turn along the stroke.
    pub follow_path: bool,
    /// The pen tilt turns the dabs.
    pub tilt_angle: bool,
    /// What the pen pressure changes.
    pub pressure: PressureCurves,
}

impl Default for BrushSettings {
    fn default() -> Self {
        Self {
            size: 40.0,
            flow: 0.8,
            opacity: 1.0,
            hardness: 0.6,
            spacing: 0.1,
            angle: 0.0,
            smoothing: 0.0,
            alpha: None,
            size_jitter: 0.0,
            angle_jitter: 0.0,
            flow_jitter: 0.0,
            scatter: 0.0,
            follow_path: false,
            tilt_angle: false,
            pressure: PressureCurves::default(),
        }
    }
}

/// A named brush.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct BrushPreset {
    /// Name shown in the list: a translation key for shipped presets.
    pub name: String,
    /// Brush settings.
    pub brush: BrushSettings,
    /// Painted material; `None` keeps the current one.
    pub material: Option<PresetMaterial>,
}

/// The shipped presets, generated by code; their names are translation keys.
pub fn shipped() -> Vec<BrushPreset> {
    let full_turn = std::f32::consts::PI;
    let preset = |name: &str, brush: BrushSettings| BrushPreset {
        name: name.to_owned(),
        brush,
        material: None,
    };
    vec![
        preset("preset-standard", BrushSettings::default()),
        preset(
            "preset-airbrush",
            BrushSettings {
                size: 120.0,
                flow: 0.12,
                hardness: 0.0,
                spacing: 0.05,
                pressure: PressureCurves {
                    size: Curve::constant(1.0),
                    flow: Curve::identity(),
                    opacity: Curve::constant(1.0),
                },
                ..BrushSettings::default()
            },
        ),
        preset(
            "preset-hard-felt",
            BrushSettings {
                size: 20.0,
                flow: 1.0,
                hardness: 1.0,
                spacing: 0.05,
                pressure: PressureCurves {
                    size: Curve(vec![[0.0, 0.6], [1.0, 1.0]]),
                    flow: Curve::constant(1.0),
                    opacity: Curve::identity(),
                },
                ..BrushSettings::default()
            },
        ),
        preset(
            "preset-chalk",
            BrushSettings {
                size: 50.0,
                flow: 0.7,
                hardness: 0.8,
                spacing: 0.15,
                alpha: Some("alpha.grain".to_owned()),
                size_jitter: 0.3,
                angle_jitter: full_turn,
                flow_jitter: 0.4,
                ..BrushSettings::default()
            },
        ),
        preset(
            "preset-splatter",
            BrushSettings {
                size: 60.0,
                flow: 1.0,
                hardness: 0.9,
                spacing: 0.6,
                alpha: Some("alpha.splatter".to_owned()),
                size_jitter: 0.6,
                angle_jitter: full_turn,
                scatter: 1.5,
                pressure: PressureCurves::none(),
                ..BrushSettings::default()
            },
        ),
        preset(
            "preset-scratches",
            BrushSettings {
                size: 14.0,
                flow: 0.9,
                hardness: 0.9,
                spacing: 0.05,
                alpha: Some("alpha.chisel".to_owned()),
                follow_path: true,
                ..BrushSettings::default()
            },
        ),
    ]
}

/// Translation keys of the shipped presets' names, for tests.
pub const SHIPPED_KEYS: [&str; 6] = [
    "preset-standard",
    "preset-airbrush",
    "preset-hard-felt",
    "preset-chalk",
    "preset-splatter",
    "preset-scratches",
];

impl BrushSettings {
    /// Copies the settings into `brush` (its material, projection and alpha image stay).
    pub fn apply_to(&self, brush: &mut BrushSnapshot) {
        brush.size = self.size;
        brush.flow = self.flow;
        brush.opacity = self.opacity;
        brush.hardness = self.hardness;
        brush.spacing = self.spacing;
        brush.angle = self.angle;
        brush.size_jitter = self.size_jitter;
        brush.angle_jitter = self.angle_jitter;
        brush.flow_jitter = self.flow_jitter;
        brush.scatter = self.scatter;
        brush.follow_path = self.follow_path;
        brush.tilt_angle = self.tilt_angle;
        brush.pressure = self.pressure.clone();
    }
}

/// The shipped preset whose name key is `preset-<name>`.
pub fn find_shipped(name: &str) -> Option<BrushPreset> {
    let key = format!("preset-{name}");
    shipped().into_iter().find(|preset| preset.name == key)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_presets_are_valid() {
        let presets = shipped();
        let names: Vec<&str> = presets.iter().map(|p| p.name.as_str()).collect();
        assert_eq!(names, SHIPPED_KEYS);
        for preset in &presets {
            assert!(
                preset.material.is_none(),
                "{} keeps the material",
                preset.name
            );
            if let Some(alpha) = &preset.brush.alpha {
                assert!(crate::alphas::find(alpha).is_some(), "{alpha}");
            }
            assert!(preset.brush.size > 0.0 && preset.brush.spacing > 0.0);
        }
        assert_eq!(
            find_shipped("chalk").map(|p| p.name),
            Some("preset-chalk".into())
        );
        assert_eq!(find_shipped("nothing"), None);
    }

    #[test]
    fn settings_reach_the_snapshot() {
        let chalk = find_shipped("chalk").expect("shipped");
        let mut brush = BrushSnapshot {
            size: 1.0,
            size_space: patine_core::stroke::SizeSpace::Screen,
            flow: 0.0,
            opacity: 0.0,
            hardness: 0.0,
            spacing: 1.0,
            angle: 0.0,
            size_jitter: 0.0,
            angle_jitter: 0.0,
            flow_jitter: 0.0,
            scatter: 0.0,
            follow_path: false,
            alpha: None,
            material: patine_core::layer::FillSource::Uniform(Default::default()),
            pressure: PressureCurves::none(),
            tilt_angle: false,
            projection: BrushSnapshot::default_projection(),
        };
        chalk.brush.apply_to(&mut brush);
        assert_eq!(brush.size, chalk.brush.size);
        assert_eq!(brush.size_jitter, chalk.brush.size_jitter);
        assert_eq!(brush.angle_jitter, chalk.brush.angle_jitter);
        assert_eq!(brush.pressure, chalk.brush.pressure);
    }
}
