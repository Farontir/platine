//! Brush engine: stroke sampling, screen-to-UV projection and `rasterize_dabs`.
//!
//! A stroke is a list of dabs in screen space, with the camera it was painted with. To
//! rasterize it into a texture set, every texel finds its point on the surface (from the
//! surface map of [`patine_procedural::surface`]), projects it with the stroke's camera
//! and reads the dabs there. The same code paints live and replays strokes, so that a
//! replay gives what the user saw.
//!
//! - [`sampler`]: pointer positions to dabs (spacing, smoothing).
//! - [`dynamics`]: the dabs as the shaders read them (pressure, jitters, path).
//! - [`symmetry`]: the copies of a stroke.
//! - [`alphas`]: the brush alphas shipped with the application, generated by code.
//! - [`projection`]: the stroke's camera, and the tiles a batch of dabs touches.
//! - [`raster`]: the GPU passes: depth, `rasterize_dabs`, composition, undo tiles.
//! - [`reference`]: the CPU mirror of the shaders.

pub mod alphas;
pub mod dynamics;
pub mod projection;
pub mod raster;
pub mod reference;
pub mod sampler;
pub mod symmetry;

/// How far beyond the UV islands painting reaches, in texels. Texels around an island
/// take the paint of their nearest surface point, so that filtering and mips do not
/// bring the background into the seams; farther texels are left alone, which keeps the
/// tiles a dab touches local.
pub const DILATION: f32 = 8.0;

/// Range of N·V (normal against the direction to the camera) over which dabs fade in:
/// surfaces seen edge-on, where a dab would smear along the surface, get no paint.
pub const GRAZING: [f32; 2] = [0.05, 0.3];

/// Relative tolerance of the occlusion test: a point is visible when its distance to the
/// camera is at most the depth seen there times `1 + DEPTH_BIAS`.
pub const DEPTH_BIAS: f32 = 0.01;
